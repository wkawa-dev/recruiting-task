-- Customers: one row per customer; its row lock serialises that customer's load decisions.
create table customer (
    customer_id varchar(255) not null,
    constraint pk_customer primary key (customer_id)
);

-- Every decided (non-duplicate) load attempt, accepted or declined.
create table load_attempt (
    id             bigint generated by default as identity,
    load_id        varchar(255)                not null,
    customer_id    varchar(255)                not null,
    amount         numeric(19, 2)              not null,
    load_time      timestamp(6) with time zone not null,
    accepted       boolean                     not null,
    decline_reason varchar(32),
    constraint pk_load_attempt primary key (id),
    constraint uk_load_attempt_customer_load unique (customer_id, load_id),
    constraint fk_load_attempt_customer foreign key (customer_id) references customer (customer_id),
    constraint ck_load_attempt_amount_positive check (amount > 0),
    constraint ck_load_attempt_decline_reason check (
        (accepted and decline_reason is null)
        or (not accepted and decline_reason in
            ('DAILY_LOAD_COUNT_EXCEEDED', 'DAILY_AMOUNT_EXCEEDED', 'WEEKLY_AMOUNT_EXCEEDED')))
);

-- Serves the per-customer time-window aggregates.
create index idx_load_attempt_customer_time on load_attempt (customer_id, load_time);
